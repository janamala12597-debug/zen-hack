export function getVoiceExplanation(
  lang: 'en' | 'te',
  crop: string,
  triggerType: 'below' | 'above',
  threshold: number,
  payout: number,
  verifiedRainfall?: number,
  status?: string
): string {
  if (lang === 'te') {
    let text = `నమస్కారం! మీ అగ్రిషీల్డ్ భీమా పాలసీ ${crop} పంటకు వర్తిస్తుంది. `;
    if (triggerType === 'below') {
      text += `ధృవీకరించబడిన వర్షపాతం ${threshold} మిల్లీమీటర్ల కంటే తక్కువగా నమోదైతే, మీకు పది వేల రూపాయల పరిహారం లభిస్తుంది. `;
    } else {
      text += `ధృవీకరించబడిన వర్షపాతం ${threshold} మిల్లీమీటర్ల కంటే ఎక్కువగా నమోదైతే, మీకు పది వేల రూపాయల పరిహారం లభిస్తుంది. `;
    }
    if (verifiedRainfall !== undefined) {
      text += `ప్రస్తుత నిర్ధారిత వర్షపాతం ${verifiedRainfall} మిల్లీమీటర్లు. `;
    }
    if (status === 'approved' || status === 'completed') {
      text += `మీ క్లెయిమ్ విజయవంతంగా ఆమోదించబడింది! `;
    }
    return text;
  }

  // English
  let text = `Hello! Your AgriShield policy covers ${crop} crops. `;
  if (triggerType === 'below') {
    text += `If verified rainfall is below ${threshold} millimetres, your payout will be ${payout.toLocaleString(
      'en-IN'
    )} rupees. `;
  } else {
    text += `If verified rainfall exceeds ${threshold} millimetres, your payout will be ${payout.toLocaleString(
      'en-IN'
    )} rupees. `;
  }
  if (verifiedRainfall !== undefined) {
    text += `Currently, the 3-oracle verified rainfall is ${verifiedRainfall} millimetres. `;
  }
  if (status === 'approved' || status === 'completed') {
    text += `Your claim has been verified and approved! `;
  }
  return text;
}
